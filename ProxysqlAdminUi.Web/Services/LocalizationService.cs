    public event Action? Changed;

    public string CurrentLanguage { get; private set; } = "en-US";

    public CultureInfo CurrentCulture => CultureInfo.GetCultureInfo(CurrentLanguage);

    public string this[string key] => CurrentLanguage.StartsWith("zh", StringComparison.OrdinalIgnoreCase)
        ? Chinese.GetValueOrDefault(key, key)
        : key;

    public string Get(string key) => this[key];

    public void SetLanguage(string language)
    {
        var normalized = language.StartsWith("zh", StringComparison.OrdinalIgnoreCase) ? "zh-CN" : "en-US";
        if (CurrentLanguage == normalized)
        {
            return;
        }

        CurrentLanguage = normalized;
        CultureInfo.CurrentCulture = CurrentCulture;
        CultureInfo.CurrentUICulture = CurrentCulture;
        Changed?.Invoke();
    }
